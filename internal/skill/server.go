package skill

import (
	"fmt"
	"strings"
	"unicode"

	"github.com/modelcontextprotocol/go-sdk/mcp"
)

// ToolInfo is what a server skill says about one tool.
type ToolInfo struct {
	Name        string
	Description string
	Destructive bool
}

// FromTools converts discovered tools; destructive says which ones need --yes.
func FromTools(tools []*mcp.Tool, destructive func(*mcp.Tool) bool) []ToolInfo {
	out := make([]ToolInfo, 0, len(tools))
	for _, t := range tools {
		d := t.Description
		if d == "" {
			d = t.Title
		}
		out = append(out, ToolInfo{Name: t.Name, Description: firstSentence(d), Destructive: destructive(t)})
	}
	return out
}

// SkillName is the skill name for a server: "mcpsh-" plus the server name in kebab-case.
func SkillName(server string) string {
	var b strings.Builder
	dash := false
	for _, r := range strings.ToLower(server) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
			dash = false
		} else if !dash {
			b.WriteByte('-')
			dash = true
		}
	}
	name := "mcpsh-" + strings.Trim(b.String(), "-")
	name = strings.TrimRight(name, "-")
	if len(name) > 64 {
		name = strings.TrimRight(name[:64], "-")
	}
	return name
}

// ForServer builds a skill for one server. about, when set, says what the server is for (the
// agent uses the description to decide when to load the skill); otherwise the tool list does.
func ForServer(server, about string, tools []ToolInfo) *Skill {
	var desc string
	if about != "" {
		desc = strings.TrimSpace(about)
		if !strings.HasSuffix(desc, ".") {
			desc += "."
		}
		desc += fmt.Sprintf(" Use it through the mcpsh CLI (server %q).", server)
	} else {
		desc = fmt.Sprintf("Use the %q MCP server through the mcpsh CLI. Its tools:", server)
	}
	// Append tool names (with short descriptions while they fit) within the length limit.
	parts := make([]string, 0, len(tools))
	for _, t := range tools {
		p := t.Name
		if t.Description != "" {
			p += " (" + truncateRunes(t.Description, 80) + ")"
		}
		parts = append(parts, p)
	}
	if about == "" {
		desc = fitList(desc+" ", parts, MaxDescription)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# The %s MCP server\n\n", server)
	if about != "" {
		fmt.Fprintf(&b, "%s\n\n", strings.TrimSpace(about))
	}
	fmt.Fprintf(&b, "Use it through `mcpsh` (see the `mcpsh` skill for the general rules). Before calling a\n")
	fmt.Fprintf(&b, "tool, read its parameters:\n\n```sh\nmcpsh %s <tool> --help\n```\n\n", server)
	fmt.Fprintf(&b, "## Tools\n\n")
	for _, t := range tools {
		line := "- `" + t.Name + "`"
		if t.Description != "" {
			line += ": " + t.Description
		}
		if t.Destructive {
			line += " **Destructive: needs `--yes`, only after the user agreed.**"
		}
		b.WriteString(line + "\n")
	}
	fmt.Fprintf(&b, "\nThis list was generated by `mcpsh skill generate %s`; `mcpsh %s` shows the current tools.\n", server, server)
	fmt.Fprintf(&b, "\n## Calling\n\n```sh\nmcpsh %s <tool> --param value\nmcpsh %s <tool> --json '{\"param\": \"value\"}' --output json\n```\n", server, server)
	return &Skill{Name: SkillName(server), Description: desc, Body: b.String()}
}

// fitList appends items separated by "; " while the result stays within max runes, ending with
// "and N more." when some do not fit.
func fitList(prefix string, items []string, max int) string {
	out := prefix
	for i, it := range items {
		sep := ""
		if i > 0 {
			sep = "; "
		}
		rest := len(items) - i - 1
		tail := "."
		if rest > 0 {
			tail = fmt.Sprintf("; and %d more.", rest)
		}
		if len([]rune(out+sep+it+tail)) > max {
			return strings.TrimSuffix(out, " ") + fmt.Sprintf(" and %d more.", len(items)-i)
		}
		out += sep + it
	}
	return out + "."
}

func firstSentence(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	for i, r := range s {
		if r == '.' && (i+1 == len(s) || unicode.IsSpace(rune(s[i+1]))) {
			return s[:i+1]
		}
	}
	return s
}

func truncateRunes(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return strings.TrimSpace(string(r[:n-1])) + "…"
}
