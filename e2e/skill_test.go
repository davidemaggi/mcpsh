package e2e

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func readFile(t *testing.T, p string) string {
	t.Helper()
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatalf("%v", err)
	}
	return string(b)
}

func TestSkills(t *testing.T) {
	e := newEnv(t, modeDirect)
	home := filepath.Join(e.root, "home")
	mustMkdir(t, home)
	e.vars["HOME"], e.vars["USERPROFILE"], e.vars["CLAUDE_CONFIG_DIR"] = home, home, ""
	e.userConfig(map[string]any{"ts": ts(nil)})

	// Project scope, every agent.
	r := e.run("skill", "install", "--scope", "project")
	expect(t, r, 0, "created", "")
	claude := readFile(t, filepath.Join(e.project, ".claude", "skills", "mcpsh", "SKILL.md"))
	shared := readFile(t, filepath.Join(e.project, ".agents", "skills", "mcpsh", "SKILL.md"))
	setup := readFile(t, filepath.Join(e.project, ".agents", "skills", "mcpsh-setup", "SKILL.md"))
	if !strings.Contains(claude, "allowed-tools: Bash(mcpsh *)") || strings.Contains(shared, "allowed-tools") {
		t.Errorf("allowed-tools must be in the Claude copy only")
	}
	if !strings.HasPrefix(setup, "---\nname: mcpsh-setup\n") || !strings.Contains(setup, "mcpsh add <name>") {
		t.Errorf("setup skill:\n%s", setup)
	}
	if !strings.Contains(r.stdout, `prefix_rule(pattern=["mcpsh"]`) {
		t.Errorf("missing the Codex permission hint: %s", r)
	}
	expect(t, e.run("skill", "install", "--scope", "project"), 0, "unchanged", "")

	// User scope, Copilot only.
	expect(t, e.run("skill", "install", "--target", "copilot", "--skill", "mcpsh"), 0, "created", "")
	if _, err := os.Stat(filepath.Join(home, ".copilot", "skills", "mcpsh", "SKILL.md")); err != nil {
		t.Error(err)
	}
	if _, err := os.Stat(filepath.Join(home, ".copilot", "skills", "mcpsh-setup")); err == nil {
		t.Error("--skill mcpsh also installed mcpsh-setup")
	}

	// A skill written by someone else is never overwritten without --force.
	foreign := filepath.Join(home, ".claude", "skills", "mcpsh", "SKILL.md")
	mustMkdir(t, filepath.Dir(foreign))
	if err := os.WriteFile(foreign, []byte("---\nname: mcpsh\ndescription: mine\n---\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	expect(t, e.run("skill", "install", "--target", "claude"), 2, "", "was not generated by mcpsh")
	if readFile(t, foreign) != "---\nname: mcpsh\ndescription: mine\n---\n" {
		t.Error("foreign skill modified")
	}
	expect(t, e.run("skill", "install", "--target", "claude", "--force"), 0, "updated", "")

	// A skill for one server.
	expect(t, e.run("skill", "generate", "ts", "--scope", "project", "--target", "claude"), 0, "mcpsh-ts", "")
	gen := readFile(t, filepath.Join(e.project, ".claude", "skills", "mcpsh-ts", "SKILL.md"))
	for _, want := range []string{"name: mcpsh-ts", `Use the \"ts\" MCP server through the mcpsh CLI`, "- `echo`: Echo the given text.",
		"`destroy`: Pretend to delete something. **Destructive"} {
		if !strings.Contains(gen, want) {
			t.Errorf("generated skill lacks %q:\n%s", want, gen)
		}
	}
	expect(t, e.run("skill", "generate", "ts", "--stdout", "--description", "Test helpers"), 0,
		`description: "Test helpers. Use it through the mcpsh CLI (server \"ts\")."`, "")
	expect(t, e.run("skill", "generate", "nope"), 2, "", "unknown server")
	expect(t, e.run("skill", "install", "--target", "vim"), 2, "", "--target must be")

	expect(t, e.run("agents-md"), 0, "mcpsh <server> <tool> --help", "")
}
